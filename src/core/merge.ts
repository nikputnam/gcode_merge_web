/**
 * Join several print jobs into one file that prints the objects one after another.
 *
 * The first object's start G-code opens the file and the tallest object's end G-code closes it
 * (its end G-code was written for a Z at least that high). Between objects the nozzle retracts,
 * lifts above everything printed so far, travels to where the next object begins, comes down,
 * and the machine state the next object's own start G-code would have left (E mode, E value,
 * temperatures, fan, feed) is restored, so each body runs exactly as it was sliced.
 */
import { placePoint } from './geom.ts';
import { numOrPercent, simulate, transformBody, type GcodeObject, type MachineState } from './gcode.ts';
import type { MergeSettings, Placement } from './types.ts';

export interface PreviewPath {
  kind: 'extrude' | 'travel';
  /** Flat xyz triples. */
  xyz: number[];
  objIndex: number;
}

export interface ObjectStats {
  name: string;
  height: number;
  extrusionLength: number;
  lines: number;
}

export interface MergeResult {
  gcode: string;
  preview: PreviewPath[];
  warnings: string[];
  objects: ObjectStats[];
  totalExtrusion: number;
  /** Index of the object whose end G-code was used. */
  footerFrom: number;
}

const f3 = (v: number) => {
  const s = v.toFixed(3);
  return (s.replace(/\.?0+$/, '') || '0').replace(/^-0$/, '0');
};
const f5 = (v: number) => (v.toFixed(5).replace(/\.?0+$/, '') || '0').replace(/^-0$/, '0');

function headerKey(lines: string[]): string {
  return lines.filter((l) => !/^; generated by /.test(l)).join('\n');
}

export function mergeJob(objs: GcodeObject[], placements: Placement[], settings: MergeSettings): MergeResult {
  if (objs.length === 0) throw new Error('Nothing to merge.');
  if (placements.length !== objs.length) throw new Error('One placement per object is required.');
  const warnings: string[] = [];
  const first = objs[0];
  const cfg = first.config;
  const num = (k: string, fb: number) => numOrPercent(cfg[k], NaN, fb);

  const travelFeed = (settings.travelSpeed ?? num('travel_speed', 150)) * 60;
  const travelZFeed = (settings.travelSpeed ?? (num('travel_speed_z', 0) || num('travel_speed', 150))) * 60;
  const retractLength = settings.retractLength ?? num('retract_length', 1);
  const retractFeed = (settings.retractSpeed ?? num('retract_speed', 15)) * 60;
  const unretractFeed = (settings.retractSpeed ?? (num('deretract_speed', 0) || num('retract_speed', 15))) * 60;

  // tallest object's end G-code: its final Z moves were written for a print at least that tall
  let footerFrom = 0;
  for (let i = 1; i < objs.length; i++) if (objs[i].height > objs[footerFrom].height + 1e-6) footerFrom = i;

  const firstKey = headerKey(first.header);
  for (let i = 1; i < objs.length; i++) {
    if (headerKey(objs[i].header) !== firstKey) {
      warnings.push(`${objs[i].name}: its start G-code differs from ${first.name}'s. Only the first object's start G-code is used; temperatures and fan from ${objs[i].name}'s are replayed before it starts.`);
    }
    if (objs[i].startState.relativeXYZ) warnings.push(`${objs[i].name}: its start G-code leaves relative positioning (G91) on; this is not supported.`);
  }
  for (const o of objs) for (const w of o.warnings) warnings.push(`${o.name}: ${w}`);

  const out: string[] = [...first.header];
  const owner: number[] = new Array(out.length).fill(-1);
  const emit = (line: string, obj: number) => { out.push(line); owner.push(obj); };

  emit(`; ---- gcode merge: ${objs.length} object(s) printed one after another ----`, -1);
  objs.forEach((o, i) => emit(`; object ${i + 1}: ${o.name} at X${f3(placements[i].x)} Y${f3(placements[i].y)} rot ${f3(placements[i].rot)}, ${f3(o.height)} mm tall (${o.source})`, -1));
  const c = settings.clearance;
  emit(`; clearance nozzleRadius=${c.nozzleRadius} nozzleHeight=${c.nozzleHeight} shroudRadius=${c.shroudRadius} gantryHeight=${Number.isFinite(c.gantryHeight) ? c.gantryHeight : 'none'} travelLift=${settings.travelLift}`, -1);

  let st: MachineState = { ...first.startState };
  let maxTop = 0;
  const stats: ObjectStats[] = [];

  objs.forEach((obj, k) => {
    const pl = placements[k];
    const hs = obj.startState;
    if (k > 0) {
      const prevCfg = objs[k - 1].config;
      const firmwareRetract = prevCfg.use_firmware_retraction === '1';
      emit(`; ---- object ${k + 1}: ${obj.name} ----`, k);
      if (st.relativeXYZ) { emit('G90', k); st.relativeXYZ = false; }
      if (st.relativeE !== hs.relativeE) { emit(hs.relativeE ? 'M83' : 'M82', k); st.relativeE = hs.relativeE; }
      // retract before leaving the finished object
      if (!st.firmwareRetracted && st.retracted <= 0) {
        if (firmwareRetract) { emit('G10', k); st.firmwareRetracted = true; }
        else if (retractLength > 0) {
          if (st.relativeE) emit(`G1 E-${f5(retractLength)} F${f3(retractFeed)}`, k);
          else emit(`G1 E${f5(st.e - retractLength)} F${f3(retractFeed)}`, k);
          st.e -= retractLength;
          st.retracted = retractLength;
        }
      }
      // lift clear of everything printed so far, travel, come down to where the body expects to be
      const zLift = Math.max(maxTop + settings.travelLift, st.z, obj.zAtFirstXY);
      const target = placePoint(obj.firstXY!, obj.center, pl);
      if (zLift > st.z + 1e-6) emit(`G1 Z${f3(zLift)} F${f3(travelZFeed)}`, k);
      emit(`G1 X${f3(target.x)} Y${f3(target.y)} F${f3(travelFeed)}`, k);
      if (Math.abs(obj.zAtFirstXY - zLift) > 1e-6) emit(`G1 Z${f3(obj.zAtFirstXY)} F${f3(travelZFeed)}`, k);
      st.x = target.x; st.y = target.y; st.z = obj.zAtFirstXY;
      // state the object's own start G-code would have left
      if (Number.isFinite(hs.bed) && hs.bed !== st.bed) { emit(`M140 S${f3(hs.bed)}`, k); st.bed = hs.bed; warnings.push(`${obj.name}: bed temperature ${hs.bed} differs from the previous object's; set without waiting.`); }
      if (Number.isFinite(hs.hotend) && hs.hotend !== st.hotend) { emit(`M109 S${f3(hs.hotend)}`, k); st.hotend = hs.hotend; }
      if (Number.isFinite(hs.fan) && hs.fan !== st.fan) { emit(hs.fan > 0 ? `M106 S${f3(hs.fan)}` : 'M107', k); st.fan = hs.fan; }
      if (st.firmwareRetracted && !hs.firmwareRetracted) { emit('G11', k); st.firmwareRetracted = false; }
      const bodyPrimes = hs.retracted > 0 || hs.firmwareRetracted;
      if (st.relativeE) {
        if (!bodyPrimes && st.retracted > 0) { emit(`G1 E${f5(st.retracted)} F${f3(unretractFeed)}`, k); st.retracted = 0; }
      } else if (!bodyPrimes && st.retracted > 0) {
        emit(`G92 E${f5(hs.e - st.retracted)}`, k);
        emit(`G1 E${f5(hs.e)} F${f3(unretractFeed)}`, k);
        st.e = hs.e; st.retracted = 0;
      } else {
        emit(`G92 E${f5(hs.e)}`, k);
        st.e = hs.e;
      }
      if (hs.feed > 0) emit(`G1 F${f3(hs.feed)}`, k);
      st.retracted = bodyPrimes ? hs.retracted : st.retracted;
      st.firmwareRetracted = hs.firmwareRetracted;
      st.feed = hs.feed;
    }
    const lines = transformBody(obj, pl);
    for (const l of lines) emit(l, k);
    const end = placePoint({ x: obj.endState.x, y: obj.endState.y }, obj.center, pl);
    st = { ...obj.endState, x: end.x, y: end.y };
    maxTop = Math.max(maxTop, obj.height);
    stats.push({ name: obj.name, height: obj.height, extrusionLength: obj.extrusionLength, lines: lines.length });
  });

  // end G-code, with the machine state its own job would have had
  const fo = objs[footerFrom];
  emit(`; ---- end G-code from ${fo.name} ----`, -1);
  if (st.relativeXYZ) emit('G90', -1);
  if (st.relativeE !== fo.endState.relativeE) emit(fo.endState.relativeE ? 'M83' : 'M82', -1);
  if (!fo.endState.relativeE) emit(`G92 E${f5(fo.endState.e)}`, -1);
  const bodyEnd = out.length;
  for (const l of fo.footer) emit(l, -1);

  // preview: replay everything between the start and end G-code
  const preview: PreviewPath[] = [];
  const pst: MachineState = { ...first.startState };
  let cur: PreviewPath | null = null;
  simulate(out.slice(first.header.length, bodyEnd), pst, (m, li) => {
    const idx = owner[first.header.length + li];
    const kind: PreviewPath['kind'] = m.de > 0 && m.hasXY ? 'extrude' : 'travel';
    if (!cur || cur.kind !== kind || cur.objIndex !== idx) {
      cur = { kind, xyz: [m.from.x, m.from.y, m.from.z], objIndex: idx };
      preview.push(cur);
    }
    cur.xyz.push(m.to.x, m.to.y, m.to.z);
  });

  return {
    gcode: out.join('\n') + '\n',
    preview,
    warnings,
    objects: stats,
    totalExtrusion: stats.reduce((a, s) => a + s.extrusionLength, 0),
    footerFrom,
  };
}
